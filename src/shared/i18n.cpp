// v0.20: language registry. Order must match the finish-page combo.
struct LangEntry { const char* code; const std::unordered_map<std::string,std::wstring>* table; };
static const LangEntry g_langs[] = {
    {"zh",     &g_zh},
    {"en",     &g_en},
    {"ja",     &g_ja},
    {"ko",     &g_ko},
    {"ru",     &g_ru},
    {"de",     &g_de},
    {"fr",     &g_fr},
    {"es",     &g_es},
    {"it",     &g_it},
    {"pt-BR",  &g_ptbr},
};

void i18n_set_language(const std::string& lang) {
    for (const auto& e : g_langs) {
        if (lang == e.code) { g_lang = lang; return; }
    }
    g_lang = "zh";
}

static const std::unordered_map<std::string, std::wstring>& current_table() {
    for (const auto& e : g_langs) {
        if (g_lang == e.code) return *e.table;
    }
    return g_zh;
}

static const std::wstring& lookup(const char* key) {
    static const std::wstring s_unknown = L"?";
    auto ov = g_overrides.find(key);
    if (ov != g_overrides.end()) return ov->second;
    const auto& table = current_table();
    auto it = table.find(key);
    if (it == table.end()) return s_unknown;
    return it->second;
}

std::wstring i18n_w(const char* key) {
    return lookup(key);
}

std::string i18n_current_lang() {
    return g_lang;
}

std::string i18n(const char* key) {
    const std::wstring& w = lookup(key);
    if (w.empty()) return "";
    int n = ::WideCharToMultiByte(CP_UTF8, 0, w.c_str(), (int)w.size(), nullptr, 0, nullptr, nullptr);
    std::string out(n, '\0');
    ::WideCharToMultiByte(CP_UTF8, 0, w.c_str(), (int)w.size(), out.data(), n, nullptr, nullptr);
    return out;
}


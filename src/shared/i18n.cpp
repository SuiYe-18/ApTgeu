static std::unordered_map<std::string, std::wstring> g_overrides;  // v0.16

void i18n_override(const char* key, const std::string& value) {
    // UTF-8 -> wide
    int len = MultiByteToWideChar(CP_UTF8, 0, value.c_str(), (int)value.size(), nullptr, 0);
    std::wstring wval(len, 0);
    MultiByteToWideChar(CP_UTF8, 0, value.c_str(), (int)value.size(), &wval[0], len);
    g_overrides[key] = wval;
}

